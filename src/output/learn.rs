//! `--learn` export: write observed patterns back to bundle `.toml` files.
//!
//! We group by `bundle_id`; for each group we emit a file at
//! `<out_dir>/<bundle_id>.toml` with `[meta]` + the top-N observed
//! skeletons as `[[pattern]]` entries. Patterns below `min_count` are
//! omitted (noise suppression).

use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::path::Path;

use color_eyre::eyre::{Context, Result};

use crate::engine::pattern::PatternSnapshot;

pub struct LearnConfig<'a> {
    pub out_dir: &'a Path,
    pub min_count: u64,
    pub top: usize,
}

pub fn write(snaps: &[PatternSnapshot], cfg: &LearnConfig<'_>) -> Result<usize> {
    fs::create_dir_all(cfg.out_dir)
        .with_context(|| format!("creating {}", cfg.out_dir.display()))?;

    // BTreeMap so output is ordering-stable (diffs cleanly across runs).
    let mut by_bundle: BTreeMap<String, Vec<&PatternSnapshot>> = BTreeMap::new();
    for s in snaps {
        if s.count < cfg.min_count {
            continue;
        }
        by_bundle
            .entry(s.bundle_id.to_string())
            .or_default()
            .push(s);
    }

    let mut files_written = 0usize;
    for (bundle, mut group) in by_bundle {
        group.sort_by_key(|s| std::cmp::Reverse(s.count));
        group.truncate(cfg.top);
        let safe = bundle.replace('/', "__");
        let path = cfg.out_dir.join(format!("{safe}.toml"));

        let mut f =
            fs::File::create(&path).with_context(|| format!("creating {}", path.display()))?;
        writeln!(f, "# Auto-generated by logfold --learn.")?;
        writeln!(f, "# Source bundle: {bundle}")?;
        writeln!(f)?;
        writeln!(f, "[meta]")?;
        writeln!(f, "id          = \"learned/{safe}\"")?;
        writeln!(f, "name        = \"Learned from {bundle}\"")?;
        writeln!(f, "category    = \"learned\"")?;
        writeln!(f, "description = \"Patterns observed at runtime.\"")?;
        writeln!(f)?;
        writeln!(f, "[detect]")?;
        writeln!(f, "line_probes = []")?;
        writeln!(f)?;
        for s in group {
            writeln!(f, "[[pattern]]")?;
            writeln!(f, "skeleton = {:?}", s.skeleton.as_str())?;
            writeln!(f, "label    = \"learned (seen {}×)\"", s.count)?;
            writeln!(f, "severity = \"info\"")?;
            writeln!(f)?;
        }
        files_written += 1;
    }
    Ok(files_written)
}
